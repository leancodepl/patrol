import 'package:file/file.dart';
import 'package:file/memory.dart';
import 'package:mocktail/mocktail.dart';
import 'package:patrol_cli/src/base/exceptions.dart';
import 'package:patrol_cli/src/base/logger.dart';
import 'package:patrol_cli/src/crossplatform/test_manifest.dart';
import 'package:patrol_cli/src/devices.dart';
import 'package:patrol_cli/src/ios/xcode_runner_setup.dart';
import 'package:test/test.dart';

const _macosRunnerLine = 'PATROL_INTEGRATION_TEST_MACOS_RUNNER(RunnerUITests)';

const _manifest = '''
{"group":{"name":"","type":"group","skip":false,"entries":[
  {"name":"example_test","type":"group","skip":false,"entries":[
    {"name":"taps once","type":"test","skip":false},
    {"name":"taps twice","type":"test","skip":false}
  ]},
  {"name":"macos.app_test","type":"group","skip":false,"entries":[
    {"name":"opens","type":"test","skip":false}
  ]}
]}}
''';

void main() {
  late FileSystem fs;
  late Directory root;
  late XcodeRunnerSetup ios;
  late XcodeRunnerSetup macos;

  setUp(() {
    fs = MemoryFileSystem.test();
    root = fs.directory('/project')..createSync();
    final logger = _MockLogger();
    ios = XcodeRunnerSetup.ios(fs: fs, rootDirectory: root, logger: logger);
    macos = XcodeRunnerSetup.macos(fs: fs, rootDirectory: root, logger: logger);
  });

  File macosRunner() => root.childFile('macos/RunnerUITests/RunnerUITests.m');

  void writeManifest() {
    for (final file in [
      root.childFile('build/patrol/patrol_test_manifest.json'),
      TestManifest.buildFile(root, TargetPlatform.macOS),
    ]) {
      file
        ..createSync(recursive: true)
        ..writeAsStringSync(_manifest);
    }
  }

  void writeMacosRunner(String contents) {
    macosRunner()
      ..createSync(recursive: true)
      ..writeAsStringSync(contents);
  }

  const includedRunner =
      '$_macosRunnerLine\n'
      '#if __has_include("PatrolGeneratedTests.inc")\n'
      '#include "PatrolGeneratedTests.inc"\n'
      '#endif\n';

  Matcher toolExitWith(String message) => throwsA(
    isA<ToolExit>().having((e) => e.message, 'message', contains(message)),
  );

  group('discoverySetupProblem', () {
    test('is null when the macOS runner includes the generated tests', () {
      writeMacosRunner(includedRunner);

      expect(macos.discoverySetupProblem(), isNull);
    });

    test('names the macOS macro when the include is missing', () {
      writeMacosRunner('$_macosRunnerLine\n');

      expect(
        macos.discoverySetupProblem(),
        allOf(
          contains('macos/RunnerUITests/RunnerUITests.m'),
          contains('right after $_macosRunnerLine'),
          contains('#include "PatrolGeneratedTests.inc"'),
        ),
      );
    });

    test('looks only at the runner of its own platform', () {
      writeMacosRunner('$_macosRunnerLine\n');

      expect(ios.discoverySetupProblem(), isNull);
    });
  });

  group('prepareBuild on macOS', () {
    test('stops when discovery is on and the include is missing', () {
      writeMacosRunner('$_macosRunnerLine\n');

      expect(
        () => macos.prepareBuild(emitTestManifest: true),
        toolExitWith('--no-emit-test-manifest'),
      );
      expect(macosRunner().readAsStringSync(), '$_macosRunnerLine\n');
    });

    test('never edits the runner when discovery is off', () {
      writeMacosRunner('$_macosRunnerLine\n');

      macos.prepareBuild(emitTestManifest: false);

      expect(macosRunner().readAsStringSync(), '$_macosRunnerLine\n');
      expect(macos.generatedIncFile.existsSync(), isFalse);
    });

    test('empties a stale .inc and drops the previous mode', () {
      writeMacosRunner(includedRunner);
      writeManifest();
      macos
        ..generateTests(
          root.childFile('build/patrol/patrol_test_manifest.json').path,
        )
        ..recordBuild(emitTestManifest: true);
      expect(macos.hasGeneratedTests, isTrue);

      macos.prepareBuild(emitTestManifest: false);

      expect(
        macos.generatedIncFile.readAsStringSync(),
        isNot(contains('@interface')),
      );
      expect(macos.hasGeneratedTests, isFalse);
    });
  });

  group('macOS build-time tests', () {
    setUp(() {
      writeMacosRunner(includedRunner);
      writeManifest();
      macos.generateTests(
        root.childFile('build/patrol/patrol_test_manifest.json').path,
      );
    });

    test('are generated next to the macOS runner', () {
      final inc = macos.generatedIncFile.readAsStringSync();
      expect(inc, contains('// Generated by `patrol build macos`'));
      expect(
        inc,
        contains(
          '@interface PatrolGeneratedTests_macos_app_test : RunnerUITests',
        ),
      );
    });

    test('record their mode with the macOS build', () {
      macos.recordBuild(emitTestManifest: true);

      expect(
        root
            .childFile('build/macos_integ/patrol_test_discovery_mode')
            .readAsStringSync(),
        'build-time',
      );
      expect(macos.hasGeneratedTests, isTrue);
    });

    test('map a file to its class and a test name to its method', () {
      macos.recordBuild(emitTestManifest: true);

      expect(
        macos.onlyTestingFor([
          'patrol_test/macos/app_test.dart',
          'example_test taps twice',
        ]),
        [
          'PatrolGeneratedTests_macos_app_test',
          'PatrolGeneratedTests_example_test/test_taps_twice',
        ],
      );
      expect(macos.onlyTestingFor(const []), [
        'PatrolGeneratedTests_example_test',
        'PatrolGeneratedTests_macos_app_test',
      ]);
    });

    test('reject --only after a runtime-discovery build', () {
      macos.recordBuild(emitTestManifest: false);

      expect(macos.hasGeneratedTests, isFalse);
      expect(macos.onlyTestingFor(const []), isEmpty);
      expect(
        () => macos.onlyTestingFor(['example_test taps once']),
        toolExitWith('patrol build macos'),
      );
    });
  });
}

class _MockLogger extends Mock implements Logger {}
