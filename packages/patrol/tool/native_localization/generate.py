#!/usr/bin/env python3
"""Generates Patrol's native-dialog localization resources from the data files.

  ios-dialog-strings.json     -> darwin/.../Resources/<locale>.lproj/Localizable.strings
  android-dialog-strings.json -> android/src/main/res/values[-<qualifier>]/strings.xml

Patrol's native automation finds system UI elements (permission dialogs,
settings toggles, photo picker, ...) by their label, so these files must
contain the exact text the OS shows. Don't edit the generated files by hand:
change the JSON (or the overrides below) and rerun this script.

Usage:
  python3 generate.py          # regenerate resources
  python3 generate.py --check  # fail if resources are out of date
"""

import json
import pathlib
import shutil
import sys

TOOL_DIR = pathlib.Path(__file__).resolve().parent
PACKAGE_DIR = TOOL_DIR.parent.parent
IOS_RESOURCES = PACKAGE_DIR / "darwin/patrol/Sources/PatrolImpl/Resources"
ANDROID_RESOURCES = PACKAGE_DIR / "android/src/main/res"

# Keys of Localizable.strings, grouped as they are used in the automators.
IOS_GROUPS = [
    ("Permission dialog buttons", [
        "ok", "allow", "allow_once", "allow_while_using_app", "dont_allow",
        "limit_access", "allow_full_access",
    ]),
    ("Notification identifiers", ["open"]),
    ("Settings navigation", [
        "developer", "dark_appearance", "display_brightness", "dark", "light",
    ]),
    ("Location precision", ["precise_off", "precise_on"]),
    ("Gallery", ["add"]),
    ("Uninstall app", ["remove_app", "delete_app", "delete"]),
]

# Apple locale names from the data file -> .lproj folder names. Folders follow
# Xcode's naming so that Bundle.preferredLocalizations can match them against
# Locale.preferredLanguages (e.g. "zh-Hant-TW" -> zh-Hant, "es-MX" -> es-419).
IOS_FOLDER_NAMES = {
    "zh_CN": "zh-Hans",
    "zh_TW": "zh-Hant",
    "zh_HK": "zh-HK",
    "no": "nb",
}

# Locales that are not generated. Locales identical to "en" are skipped
# automatically, because they fall back to en.lproj.
IOS_SKIPPED = {
    "pt": "incomplete (2 of 19 keys); Portuguese devices use pt-BR or pt-PT",
    "yue_CN": "incomplete (4 of 19 keys)",
}

# Values that Patrol shipped (and tested on devices in CI) before the data
# file was introduced and that differ from it. They take precedence until
# someone confirms on a device which variant the current iOS version shows.
IOS_VERIFIED_OVERRIDES = {
    "de": {"developer": "Entwickler", "add": "Hinzufügen"},
    "fr": {
        "allow_while_using_app": "Autoriser pendant l'utilisation de l'app",
        "precise_off": "Précis : Désactivé",
        "precise_on": "Précis : Activé",
    },
    "ja": {"remove_app": "アプリを取り除く"},
    "pl": {
        "allow": "Pozwalaj",
        "dark_appearance": "Ciemny wygląd",
        "precise_off": "Dokładne: Wył.",
        "precise_on": "Dokładne: Wł.",
    },
}

# Keys left out of a locale because the source value is known to be wrong.
# Patrol reports a missing key instead of tapping the wrong element.
IOS_OMITTED_KEYS = {
    "lt": {
        "precise_off": 'source data has "Tiksli: įjungta" ("on"), same as precise_on',
    },
}

ANDROID_KEYS = [
    ("Airplane mode toggle", "airplane_mode"),
    ("Location settings", "use_location"),
    ("Photo picker confirm button (Android API 36+)", "gallery_done_button"),
]

# Values that differ between AOSP `main` (the data file) and the latest
# released Android version, which is what emulators and devices run. Checked
# against the Android 16 (API 36) Google APIs emulator image.
ANDROID_RELEASE_OVERRIDES = {
    "es-rUS": {"airplane_mode": "Modo avión"},  # AOSP main: "Modo de avión"
}

# Marker resolved at runtime to detect that the device locale fell back to the
# default (English) resources. Must match Localization.kt.
ANDROID_LOCALE_MARKER = "patrol_localization_locale"

IOS_HEADER = "/* Generated by tool/native_localization/generate.py. Do not edit. */\n"
ANDROID_HEADER = "<!-- Generated by tool/native_localization/generate.py. Do not edit. -->\n"


def escape_ios(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def escape_android(value):
    value = (
        value.replace("\\", "\\\\")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace("'", "\\'")
        .replace('"', '\\"')
    )
    if value[:1] in ("@", "?"):
        value = "\\" + value
    return value


def generate_ios(data):
    english = data["en"]
    files = {}
    for locale, strings in sorted(data.items()):
        if locale in IOS_SKIPPED or (locale != "en" and strings == english):
            continue
        strings = {**strings, **IOS_VERIFIED_OVERRIDES.get(locale, {})}
        omitted = IOS_OMITTED_KEYS.get(locale, {})
        lines = [IOS_HEADER]
        for title, keys in IOS_GROUPS:
            lines.append(f"\n/* {title} */\n")
            for key in keys:
                if key in omitted:
                    lines.append(f"/* \"{key}\" omitted: {omitted[key]} */\n")
                elif key in strings:
                    lines.append(f'"{key}" = "{escape_ios(strings[key])}";\n')
        folder = IOS_FOLDER_NAMES.get(locale, locale.replace("_", "-"))
        files[IOS_RESOURCES / f"{folder}.lproj" / "Localizable.strings"] = "".join(lines)
    return files


def generate_android(data):
    files = {}
    for qualifier, strings in sorted(data.items()):
        strings = {**strings, **ANDROID_RELEASE_OVERRIDES.get(qualifier, {})}
        lines = ['<?xml version="1.0" encoding="utf-8"?>\n', ANDROID_HEADER, "<resources>\n"]
        lines.append(f'    <string name="{ANDROID_LOCALE_MARKER}">{qualifier}</string>\n')
        for title, key in ANDROID_KEYS:
            if key in strings:
                lines.append(f"\n    <!-- {title} -->\n")
                lines.append(f'    <string name="{key}">{escape_android(strings[key])}</string>\n')
        lines.append("</resources>\n")
        folder = "values" if qualifier == "en" else f"values-{qualifier}"
        files[ANDROID_RESOURCES / folder / "strings.xml"] = "".join(lines)
    return files


def stale_paths(files):
    """Generated files and folders that no longer correspond to any locale."""
    expected_dirs = {path.parent for path in files}
    stale = [d for d in IOS_RESOURCES.glob("*.lproj") if d not in expected_dirs]
    for d in ANDROID_RESOURCES.glob("values*"):
        for f in d.glob("strings*.xml"):
            if f not in files:
                stale.append(f)
    return stale


def main():
    check = "--check" in sys.argv[1:]
    ios = json.loads((TOOL_DIR / "ios-dialog-strings.json").read_text())
    android = json.loads((TOOL_DIR / "android-dialog-strings.json").read_text())
    files = {**generate_ios(ios), **generate_android(android)}

    changed = [p for p, c in files.items() if not p.exists() or p.read_text() != c]
    stale = stale_paths(files)

    if check:
        for path in changed + stale:
            print(f"Out of date: {path.relative_to(PACKAGE_DIR)}")
        if changed or stale:
            print("Run: python3 packages/patrol/tool/native_localization/generate.py")
            sys.exit(1)
        return

    for path in stale:
        if path.is_dir():
            shutil.rmtree(path)
        else:
            path.unlink()
            if not any(path.parent.iterdir()):
                path.parent.rmdir()
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path])
    print(
        f"Generated {sum(p.parent.parent == IOS_RESOURCES for p in files)} iOS and "
        f"{sum(p.parent.parent == ANDROID_RESOURCES for p in files)} Android locales "
        f"({len(changed)} files written, {len(stale)} removed)"
    )


if __name__ == "__main__":
    main()
